#!/usr/bin/env python3
"""R109-01：生成 Gson 存档字段保名规则（R8 完整游戏实验）。

证据链：
  - savestates/**/*.json 的存档键是可读字段名（如 antimatter/auto/achievements）；
  - work/mod 解码树中 Player 存档树的字段名与存档键一一对应（smali .field 可读）；
  - 从 Lkajfosz/antimatterdimensions/player/Player* 出发沿实例字段类型求闭包。

输出：-keepclassmembers class <cls> { <fields>; }（每个存档可达类一行），
并列出闭包内 enum（R8 会重命名 enum 常量，Gson 按 name() 序列化）。

用法：python3 scripts/agp/r109_save_keepgen.py --decoded-tree work/mod --out <rules>
"""
import argparse
import collections
import os
import pathlib
import re
import sys

LIB_PREFIX = (
    "Landroid/", "Landroidx/", "Lcom/google/", "Lkotlin/", "Lkotlinx/", "Ljava/",
    "Ljavax/", "Lorg/", "Lcom/amazon/", "Lcom/skydoves/", "Lokhttp3/", "Lcom/bumptech/",
    "Lcom/airbnb/", "Lio/", "Lcom/facebook/", "Lcom/appsflyer/", "Lcom/unity3d/",
    "Lcom/fasterxml/", "Lcom/crashlytics/", "Lcom/google_", "Lcom/android/",
)
FIELD_RE = re.compile(r"^\.field\s+(?P<mods>[^\n]*?)\s(?P<name>[A-Za-z_$][A-Za-z0-9_$]*):(?P<desc>\[*(?:L[^;]+;|[BCDFIJSZ]))", re.M)
CLASS_RE = re.compile(r"^\.class[^\n]* (L[^;]+;)\s*$", re.M)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--decoded-tree", default="work/mod")
    ap.add_argument("--seed-prefix", default="Lkajfosz/antimatterdimensions/player/Player")
    ap.add_argument("--out")
    args = ap.parse_args()

    info = {}
    for sub in ("smali", "smali_classes2", "smali_classes3"):
        root = pathlib.Path(args.decoded_tree) / sub
        if not root.is_dir():
            continue
        for dirpath, _, names in os.walk(root):
            for name in names:
                if not name.endswith(".smali"):
                    continue
                path = os.path.join(dirpath, name)
                try:
                    txt = open(path, encoding="utf-8", errors="replace").read()
                except OSError:
                    continue
                m = CLASS_RE.search(txt)
                if not m:
                    continue
                fields = []
                for mm in FIELD_RE.finditer(txt):
                    mods = mm.group("mods") or ""
                    fields.append((mm.group("name"), mm.group("desc"), "static" in mods))
                info[m.group(1)] = {"fields": fields, "is_enum": ".super Ljava/lang/Enum;" in txt}

    seed = [c for c in info if c.startswith(args.seed_prefix)]
    closure = set(seed)
    frontier = list(seed)
    while frontier:
        nxt = []
        for cls in frontier:
            for _name, desc, is_static in info[cls]["fields"]:
                if is_static:
                    continue
                bt = desc
                while bt.startswith("["):
                    bt = bt[1:]
                if not bt.startswith("L") or bt.startswith(LIB_PREFIX):
                    continue
                if bt in info and bt not in closure:
                    closure.add(bt)
                    nxt.append(bt)
        frontier = nxt

    enums = sorted(c for c in closure if info[c]["is_enum"])
    lines = ["# generated by scripts/agp/r109_save_keepgen.py (Gson 存档字段保名)"]
    for cls in sorted(closure):
        java = cls[1:-1].replace("/", ".")
        lines.append("-keepclassmembers class %s { <fields>; }" % java)
    for cls in enums:
        java = cls[1:-1].replace("/", ".")
        lines.append("-keepclassmembers enum %s { *; }" % java)
    text = "\n".join(lines) + "\n"
    if args.out:
        pathlib.Path(args.out).write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    print("closure=%d enums=%d" % (len(closure), len(enums)), file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
