#!/usr/bin/env python3
"""R109-01：从 AndroidManifest.xml 提取「按名字加载」的类并生成 keep 规则。

证据：Manifest 的 android:name / android:value 里有大量运行时按类名加载的类
（组件、androidx.startup Initializer、Firebase ComponentRegistrar、
datatransport backend 等），R8 重命名会导致运行时 ClassNotFound。

输出：-keep class <cls> { *; }（仅限该 game JAR 中真实存在的类）。

用法：
  python3 scripts/agp/r109_manifest_keepgen.py --manifest work/mod/AndroidManifest.xml --game-jar <jar> --out <rules>
"""
import argparse
import pathlib
import re
import sys
import zipfile


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", default="work/mod/AndroidManifest.xml")
    ap.add_argument("--game-jar", required=True)
    ap.add_argument("--out")
    args = ap.parse_args()

    text = pathlib.Path(args.manifest).read_text(encoding="utf-8", errors="replace")
    raw = set(re.findall(r'android:name="([^"]+)"', text)) | set(re.findall(r'android:value="([^"]+)"', text))
    candidates = set()
    for value in raw:
        if value.startswith("@") or " " in value or value.startswith("http"):
            continue
        for part in value.split(":"):
            if "." in part and not part.startswith("android.permission") and ":" not in part:
                candidates.add(part)

    with zipfile.ZipFile(args.game_jar) as zf:
        entries = set(zf.namelist())
    present = sorted(c for c in candidates if c.replace(".", "/") + ".class" in entries)

    lines = ["# generated by scripts/agp/r109_manifest_keepgen.py (Manifest 按名加载的类)"]
    lines += ["-keep class %s { *; }" % c for c in present]
    out = chr(10).join(lines) + chr(10)
    if args.out:
        pathlib.Path(args.out).write_text(out, encoding="utf-8")
    else:
        sys.stdout.write(out)
    print("candidates=%d kept=%d" % (len(candidates), len(present)), file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
