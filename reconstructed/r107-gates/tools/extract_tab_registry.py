#!/usr/bin/env python3
"""Extract the vanilla 3.21 tab registry from jp4.smali.

Read-only: parses work/base_decoded_321/smali_classes2/jp4.smali, emits
  out/tab-registry-321.json
  src/gates/TabRegistry321.kt   (generated fixture consumed by the JVM test)

Why: the stage-gate name list must cover every eternity-layer tab key.
Hand-maintained lists drift; generating from the official decoded tree keeps
the fixture auditable.

Pure analysis, no game/build interaction.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]  # android/AD_Oreki_Edition_Android
SMALI = ROOT / "work/base_decoded_321/smali_classes2/jp4.smali"
OUT_JSON = ROOT / "reconstructed/r107-gates/out/tab-registry-321.json"
OUT_KT = ROOT / "reconstructed/r107-gates/src/gates/TabRegistry321.kt"

KEY_RE = re.compile(r"^[A-Za-z][A-Za-z0-9]*$")
UNI_RE = re.compile(r"\\u([0-9a-fA-F]{4})")


def smali_to_text(s: str) -> str:
    """Decode smali const-string \\uXXXX escapes into real characters (fixture only)."""
    return UNI_RE.sub(lambda m: chr(int(m.group(1), 16)), s)


def kt_str(s: str) -> str:
    """Emit a Kotlin string literal that reproduces s exactly (UTF-8 source)."""
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 0x20 <= o < 0x7f:
            out.append(ch)
        else:
            out.append("\\u%04x" % o)
    return '"' + "".join(out) + '"'
NEW_RE = re.compile(r"^\s*new-instance (v\d+), L(ll2|bm4);")
STR_RE = re.compile(r'^\s*const-string (v\d+), "(.*)"\s*$')
SPUT_RE = re.compile(r"^\s*sput-object (v\d+), Ljp4;->(\w+):L(ll2|bm4);")
CTOR_RE = re.compile(r"^\s*invoke-direct/range \{(v\d+) \.\. (v\d+)\}, L(ll2|bm4);-><init>")


def main() -> int:
    text = SMALI.read_text(encoding="utf-8")
    lines = text.splitlines()
    # isolate <clinit>
    start = next(i for i, l in enumerate(lines) if l.startswith(".method static constructor <clinit>"))
    end = next(i for i in range(start, len(lines)) if lines[i].startswith(".end method"))
    body = lines[start:end]

    parents = {}   # field -> dict(key, glyph)
    children = []  # dict(field, key, glyph, group)
    pending = None  # dict(kind, reg, strings)
    last_field = {}
    current_group = None

    for line in body:
        m = NEW_RE.match(line)
        if m:
            pending = {"kind": m.group(2), "reg": m.group(1), "strings": []}
            continue
        if pending is not None:
            ms = STR_RE.match(line)
            if ms:
                pending["strings"].append(ms.group(2))
                continue
            mc = CTOR_RE.match(line)
            if mc and mc.group(3) == pending["kind"]:
                kinds = [s for s in pending["strings"] if KEY_RE.match(s)]
                glyphs = [s for s in pending["strings"] if not KEY_RE.match(s)]
                # business key: the ASCII identifier; if several (parent: 2 groups of params),
                # the key is the one that is not a duplicated glyph. jp4 passes key once.
                key = kinds[0] if kinds else None
                glyph = glyphs[0] if glyphs else None
                pending["key"] = key
                pending["glyph"] = smali_to_text(glyph) if glyph else None
                continue
        msput = SPUT_RE.match(line)
        if msput:
            field, kind = msput.group(2), msput.group(3)
            if pending is None or pending["kind"] != kind:
                continue
            if kind == "ll2":
                parents[field] = {"key": pending["key"], "glyph": pending["glyph"]}
                current_group = pending["key"]
            else:
                children.append({
                    "field": field,
                    "key": pending["key"],
                    "glyph": pending["glyph"],
                    "group": current_group,
                })
            pending = None

    # sanity: every entry must have a key
    missing = [p for p in parents.values() if not p["key"]] + [c for c in children if not c["key"]]
    data = {
        "source": str(SMALI.relative_to(ROOT)),
        "note": "generated by toolS/extract_tab_registry.py; key = Luo4.b business key, glyph = bm4.i icon string",
        "parents": [{"field": f, "key": v["key"], "glyph": v["glyph"]} for f, v in parents.items()],
        "children": children,
        "missing_keys": missing,
    }
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    # generated Kotlin fixture: parent groups + tab keys in declaration order
    def kt_list(name, items):
        inner = ",\n".join('        ' + kt_str(s) for s in items)
        return "    val %s: List<String> = listOf(\n%s,\n    )\n" % (name, inner)

    parent_keys = [v["key"] for v in parents.values() if v["key"]]
    child_keys = [c["key"] for c in children if c["key"]]
    OUT_KT.parent.mkdir(parents=True, exist_ok=True)
    OUT_KT.write_text(
        "// GENERATED by reconstructed/r107-gates/tools/extract_tab_registry.py — do not edit.\n"
        "// Source: " + data["source"] + "\n"
        "// Vanilla 3.21 jp4 tab registry: parent group keys and child tab business keys (Luo4.b).\n"
        "package gates\n\n"
        "object TabRegistry321 {\n"
        + kt_list("parentGroupKeys", parent_keys)
        + "\n"
        + kt_list("childTabKeys", child_keys)
        + "\n"
        + kt_list("glyphs", [c["glyph"] for c in children if c["glyph"]])
        + "\n"
        + "    /** child tab business key -> parent group business key. */\n"
        "    val tabGroup: Map<String, String> = mapOf(\n"
        + ",\n".join('        "%s" to "%s"' % (c["key"], c["group"]) for c in children if c["key"])
        + ",\n    )\n"
        "}\n",
        encoding="utf-8",
    )
    print(json.dumps({"parents": len(parent_keys), "children": len(child_keys),
                      "missing_keys": len(missing), "json": str(OUT_JSON), "kt": str(OUT_KT)},
                     ensure_ascii=False))
    for c in children:
        print("%-22s group=%-18s glyph=%r" % (c["key"], c["group"], c["glyph"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())